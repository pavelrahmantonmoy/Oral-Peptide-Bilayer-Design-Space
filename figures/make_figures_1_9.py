# =============================== FIGURE 9 ===============================
# Simplified one-compartment model, Eq. (7); weekly dosing to steady state.
# Parameters varied uniformly by +/-10% about literature-guided central values,
# matching the perturbation used in the Monte Carlo analysis of Section 2.11.
rng = np.random.default_rng(42)
N, DOSE, TAU, NDOSE = 100, 15.0, 168.0, 10          # mg, h
F0, KA0, THALF0, VD0 = 0.01, 0.50, 120.0, 10.3      # -, 1/h, h, L
u = lambda c: rng.uniform(c * 0.9, c * 1.1, N)
F, KA, VD = u(F0), u(KA0), u(VD0)
KE = np.log(2) / u(THALF0)
t = np.linspace(0, TAU * NDOSE, 4000)

def profile(F, ka, ke, Vd):
    amt = F * DOSE * 1e3                     # ug
    c = np.zeros_like(t)
    for i in range(NDOSE):
        dt = t - i * TAU
        m = dt >= 0
        c[m] += amt * ka / (Vd * (ka - ke)) * (np.exp(-ke * dt[m]) - np.exp(-ka * dt[m]))
    return c                                  # ug/L = ng/mL

C = np.array([profile(F[i], KA[i], KE[i], VD[i]) for i in range(N)])
last = t >= TAU * (NDOSE - 1)
tl, Cl = t[last], C[:, last]
cmax, cmin = Cl.max(1), Cl.min(1)
cavg = np.trapezoid(Cl, tl, axis=1) / TAU
auc = np.trapezoid(Cl, tl, axis=1)
Fi = (cmax - cmin) / cavg
cv_auc = auc.std(ddof=1) / auc.mean() * 100

print('median Cmax,ss  = %.1f ng/mL' % np.median(cmax))
print('median Cmin,ss  = %.1f ng/mL' % np.median(cmin))
print('AUC_tau CV%%     = %.1f%%' % cv_auc)
print('median Fi       = %.2f' % np.median(Fi))

# Monte Carlo release envelope for the inset (Peppas-Sahlin, +/-10% on k_d, k_r)
kd0, kr0 = 9.4174, 1.9439
kd = rng.uniform(kd0 * .9, kd0 * 1.1, 1000)[:, None]
kr = rng.uniform(kr0 * .9, kr0 * 1.1, 1000)[:, None]
tr = np.linspace(0.01, 12, 200)[None, :]
Q = kd * tr ** 0.45 + kr * tr ** 0.89
q_lo, q_hi = np.percentile(Q, [2.5, 97.5], axis=0)
q_nom = kd0 * tr.ravel() ** 0.45 + kr0 * tr.ravel() ** 0.89

fig, ax = plt.subplots(figsize=(10.0, 5.5))
td = (tl - tl[0])
for i in range(N):
    ax.plot(td, Cl[i], color='#9db8d2', lw=.4, alpha=.35)
lo, hi = np.percentile(Cl, [10, 90], axis=0)
ax.fill_between(td, lo, hi, color='#9db8d2', alpha=.55, lw=0,
                label='10th–90th percentile envelope')
ax.plot(td, np.median(Cl, 0), color='#1d4e6f', lw=2.2, label='Population median')
ax.set_xlabel('Time within the steady-state dosing interval (h)', fontsize=10)
ax.set_ylabel('Plasma Tirzepatide concentration (ng/mL)', fontsize=10)
ax.set_title('Literature-guided virtual population estimate '
             '(one-compartment model, Eqs. 7–8; n = 100)', fontsize=11, weight='bold')
ax.set_xlim(0, TAU); ax.set_xticks(np.arange(0, 169, 24))
ax.grid(alpha=.25, lw=.5, ls='--')
ax.legend(loc='lower left', fontsize=8.5)
ax.text(.985, .96,
        'median $C_{max,ss}$ = %.1f ng/mL\nAUC$_{0-\\tau}$ CV = %.1f%%\nmedian fluctuation index = %.2f'
        % (np.median(cmax), cv_auc, np.median(Fi)),
        transform=ax.transAxes, ha='right', va='top', fontsize=8,
        bbox=dict(boxstyle='round,pad=0.4', fc='w', ec='#999999', lw=.7, alpha=.95))

ins = ax.inset_axes([.40, .40, .40, .45])
ins.fill_between(tr.ravel(), q_lo, q_hi, color='#ffb570', alpha=.65, lw=0,
                 label='95% envelope')
ins.plot(tr.ravel(), q_nom, color='#d62728', lw=1.8, label='Nominal')
ins.axvline(12, color='k', ls=':', lw=.8)
ins.plot(12, 46.6, 'o', ms=5, mfc='w', mec='k', mew=.9)
